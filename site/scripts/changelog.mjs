// @ts-check
/**
 * Copy each package's CHANGELOG into the docs, so the release notes are on the
 * site rather than a link out to GitHub.
 *
 * They are generated rather than committed, the same way the typedoc API pages
 * are: changesets rewrites the source files on every release, and a copy kept
 * in git would be one more thing to forget.
 */
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const siteDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const repoDir = path.dirname(siteDir)
const outDir = path.join(siteDir, 'docs', 'changelog')

/** In dependency order, which is also the order they are listed everywhere else. */
const packages = ['functions', 'dom', 'react']

/** `index.md`, the page the category links to, is position 1. */
const firstPosition = 2

const header = (name, position) => `---
title: 'Changelog: ${name}'
sidebar_label: '${name}'
sidebar_position: ${position}
# The file is written by changesets, so it has to be read as plain CommonMark.
# As MDX, a stray < or { in a release note would fail the build.
format: md
# There is nothing to edit: the page is generated, and so is the CHANGELOG it
# comes from. A release note is written as a changeset.
custom_edit_url: null
---

<!-- Generated by site/scripts/changelog.mjs. Edit the changeset, not this file. -->

`

/** Drop the leading \`# @tremolo-ui/x\`; the front matter carries the title. */
function body(source) {
  return source.replace(/^#[^\n]*\n+/, '')
}

await mkdir(outDir, { recursive: true })

// A package that has been renamed or dropped would otherwise leave its page
// behind, and it would keep showing up in the sidebar.
for (const stale of await readdir(outDir)) {
  if (stale !== 'index.md') await rm(path.join(outDir, stale))
}

for (const [index, pkg] of packages.entries()) {
  const name = `@tremolo-ui/${pkg}`
  const source = await readFile(
    path.join(repoDir, 'packages', pkg, 'CHANGELOG.md'),
    'utf8',
  )
  await writeFile(
    path.join(outDir, `${pkg}.md`),
    header(name, firstPosition + index) + body(source),
  )
  console.log(`changelog: ${name}`)
}
